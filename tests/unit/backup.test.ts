/** Rewrites checksums.sha256 and the manifest's hashes, sizes and counts after a mutation. */
function reseal(snapshot: string) {
  const walk = (sub: string): string[] =>
    readdirSync(join(snapshot, sub), { withFileTypes: true }).flatMap((entry) =>
      entry.isDirectory()
        ? walk(join(sub, entry.name))
        : [join(sub, entry.name).split('\\').join('/')],
    );
  const files = walk('')
    .filter((file) => file !== 'manifest.json' && file !== 'checksums.sha256')
    .sort();
  writeFileSync(
    join(snapshot, 'checksums.sha256'),
    files.map((file) => `${sha(readFileSync(join(snapshot, file)))}  ${file}`).join('\n') + '\n',
  );
  const manifest = JSON.parse(readFileSync(join(snapshot, 'manifest.json'), 'utf8'));
  const objects = files.filter((file) => file.startsWith('objects/'));
  manifest.objects = {
    count: objects.length,
    totalBytes: objects.reduce((sum, file) => sum + statSync(join(snapshot, file)).size, 0),
  };
  const sql = readFileSync(join(snapshot, 'database.sql'));
  manifest.database = { path: 'database.sql', sha256: sha(sql), bytes: sql.length };
  writeFileSync(join(snapshot, 'manifest.json'), JSON.stringify(manifest));
}

