describe('verify-backup', () => {
  async function validSnapshot() {
    expect(await runBackup(deps().deps)).toBe(0);
    return snapshotDir();
  }

  it('AC-BAK-02 fails on a missing image', async () => {
    const snapshot = await validSnapshot();
    rmSync(join(snapshot, 'objects/media/v1/m1/image.webp'));
    reseal(snapshot);
    const { errors } = await verifySnapshot(snapshot);
    expect(errors).toEqual(['missing object media/v1/m1/image.webp (media m1).']);
  });

  it('AC-BAK-02 fails on a truncated SQL file', async () => {
    const snapshot = await validSnapshot();
    const sql = readFileSync(join(snapshot, 'database.sql'), 'utf8');
    writeFileSync(join(snapshot, 'database.sql'), sql.slice(0, sql.indexOf("'m2'") + 10));
    reseal(snapshot);
    const { errors } = await verifySnapshot(snapshot);
    expect(errors).toEqual(['database.sql does not parse into SQLite (truncated or corrupt).']);
  });

  it('AC-BAK-02 fails on a mismatched checksum', async () => {
    const snapshot = await validSnapshot();
    const path = join(snapshot, 'objects/avatars/v1/u1/a1.webp');
    writeFileSync(path, Buffer.from('AVATAR'));
    const { errors } = await verifySnapshot(snapshot);
    expect(errors).toContain('checksum mismatch: objects/avatars/v1/u1/a1.webp.');
    expect(errors).toContain(
      'object avatars/v1/u1/a1.webp differs from its media row (size or hash).',
    );
  });

  it('R-BAK-04 fails when row counts or object totals disagree with the manifest', async () => {
    const snapshot = await validSnapshot();
    const manifest = JSON.parse(readFileSync(join(snapshot, 'manifest.json'), 'utf8'));
    manifest.tables.users = 2;
    manifest.objects.count = 6;
    writeFileSync(join(snapshot, 'manifest.json'), JSON.stringify(manifest));
    const { errors } = await verifySnapshot(snapshot);
    expect(errors).toHaveLength(2);
    expect(errors[0]).toContain('row count for users');
    expect(errors[1]).toContain('objects: 5 files');
  });

  it('R-BAK-04 fails on a file the checksums do not list', async () => {
    const snapshot = await validSnapshot();
    writeFileSync(join(snapshot, 'objects/extra'), 'x');
    expect((await verifySnapshot(snapshot)).errors).toContain(
      'objects/extra is not in checksums.sha256.',
    );
  });

  it('AC-BAK-03 rejects a directory without completed: true', async () => {
    const snapshot = await validSnapshot();
    const manifest = JSON.parse(readFileSync(join(snapshot, 'manifest.json'), 'utf8'));
    writeFileSync(
      join(snapshot, 'manifest.json'),
      JSON.stringify({ ...manifest, completed: false }),
    );
    expect((await verifySnapshot(snapshot)).errors).toEqual([
      'manifest.json lacks completed: true; this directory is not a backup.',
    ]);
    const errors: string[] = [];
    expect(await runVerifyBackup([snapshot], {}, { err: (line) => errors.push(line) })).toBe(1);
    expect(errors.join('\n')).toContain('not a backup');
    rmSync(join(snapshot, 'manifest.json'));
    expect((await verifySnapshot(snapshot)).errors).toEqual([
      'manifest.json is missing or not JSON.',
    ]);
  });

  it('R-BAK-04 the CLI passes a valid directory and needs an identity for an archive', async () => {
    const snapshot = await validSnapshot();
    const lines: string[] = [];
    const io = { out: (line: string) => lines.push(line), err: (line: string) => lines.push(line) };
    expect(await runVerifyBackup([snapshot], {}, io)).toBe(0);
    expect(lines.at(-1)).toContain('verify-backup: OK');
    const archive = join(dir, 'out', readdirSync(join(dir, 'out'))[0]!);
    expect(await runVerifyBackup([archive], {}, io)).toBe(1);
    expect(lines.at(-1)).toContain('needs the age identity');
    const identity = join(dir, 'key.txt');
    writeFileSync(identity, 'AGE-SECRET-KEY-SYNTHETIC');
    // A fake decrypt that unpacks the inspected copy, as age | tar would.
    const decrypt = async (_archive: string, _identity: string, into: string) => {
      cpSync(snapshot, join(into, 'classhub-backup-x'), { recursive: true });
    };
    expect(await runVerifyBackup([archive, '--identity', identity], {}, { ...io, decrypt })).toBe(
      0,
    );
    expect(
      await runVerifyBackup([archive], { AGE_IDENTITY_FILE: identity }, { ...io, decrypt }),
    ).toBe(0);
    expect(await runVerifyBackup([archive, '--bogus'], {}, io)).toBe(1);
  });

  it('R-BAK-04 removes its private decrypt directory, also on a failed archive', async () => {
    const scratch = join(dir, 'tmp');
    const result = await verifyArchive(join(dir, 'missing.tar.age'), join(dir, 'key.txt'), {
      tmpRoot: scratch,
      decrypt: async () => {
        throw new Error('no identity matched');
      },
    });
    expect(result.errors[0]).toContain('no identity matched');
    expect(readdirSync(scratch)).toEqual([]);
  });

  it('R-BAK-04 a signal mid-decrypt removes the decrypted snapshot', async () => {
    const scratch = join(dir, 'tmp');
    let fail: (error: Error) => void = () => {};
    let started = false;
    const running = verifyArchive(join(dir, 'x.tar.age'), join(dir, 'key.txt'), {
      tmpRoot: scratch,
      decrypt: (_archive, _identity, into) => {
        mkdirSync(join(into, 'classhub-backup-x'));
        writeFileSync(join(into, 'classhub-backup-x', 'database.sql'), 'member data');
        started = true;
        return new Promise((_resolve, reject) => (fail = reject));
      },
    });
    await vi.waitFor(() => expect(started).toBe(true));
    expect(readdirSync(scratch)).toHaveLength(1);
    runPendingCleanups();
    expect(readdirSync(scratch)).toEqual([]);
    fail(new Error('stopped'));
    await running;
  });

  it('R-BAK-04 the verify-backup CLI removes its decrypt directory and stops age on SIGTERM', async () => {
    // A fake `age` that hangs, as a large archive would, so the signal lands mid-decrypt.
    const bin = join(dir, 'bin');
    mkdirSync(bin);
    writeFileSync(join(bin, 'age'), '#!/bin/sh\nexec sleep 30\n');
    chmodSync(join(bin, 'age'), 0o755);
    const archive = join(dir, 'x.tar.age');
    writeFileSync(archive, 'not really encrypted');
    writeFileSync(join(dir, 'key.txt'), 'AGE-SECRET-KEY-SYNTHETIC');
    const scratch = join(dir, 'tmp');
    const script = fileURLToPath(new URL('../../scripts/verify-backup.mjs', import.meta.url));
    const child = spawn(process.execPath, [script, archive, '--identity', join(dir, 'key.txt')], {
      env: { PATH: `${bin}:${process.env.PATH ?? ''}`, TMPDIR: scratch },
      stdio: 'ignore',
    });
    const exited = new Promise<number | null>((resolve) => child.on('exit', resolve));
    await vi.waitFor(() => expect(readdirSync(scratch)).toHaveLength(1), { timeout: 4_000 });
    child.kill('SIGTERM');
    expect(await exited).toBe(143);
    expect(readdirSync(scratch)).toEqual([]);
  });

  it.skipIf(!ageInstalled)(
    'AC-BAK-09 with real age: the archive decrypts and verifies, the plaintext never stays',
    async () => {
      // Skipped where age is not installed; the refusal tests above never need it.
      const identity = join(dir, 'key.txt');
      expect(spawnSync('age-keygen', ['-o', identity], { stdio: 'ignore' }).status).toBe(0);
      const publicKey = spawnSync('age-keygen', ['-y', identity], {
        encoding: 'utf8',
      }).stdout.trim();
      const { deps: d, errors } = deps({ recipient: publicKey, encrypt: undefined });
      expect(await runBackup(d)).toBe(0);
      expect(errors).toEqual([]);
      const [name] = readdirSync(join(dir, 'out'));
      expect(name).toMatch(/^classhub-backup-.+\.tar\.age$/);
      const archive = join(dir, 'out', name!);
      expect(readFileSync(archive).subarray(0, 21).toString()).toBe('age-encryption.org/v1');
      expect(readFileSync(archive).includes(Buffer.from('Synthetic Member'))).toBe(false);
      expect(readdirSync(join(dir, 'tmp'))).toEqual([]);
      const result = await verifyArchive(archive, identity, { tmpRoot: join(dir, 'tmp') });
      expect(result.errors).toEqual([]);
      expect(result.manifest?.completed).toBe(true);
      expect(readdirSync(join(dir, 'tmp'))).toEqual([]);
    },
  );
});

describe('verify-backup database.sql allowlist', () => {
  const migrationsDir = fileURLToPath(new URL('../../migrations/', import.meta.url));

  it('R-BAK-04 loads a D1-shaped export of the real schema, rows, sequence, trigger and view', () => {
    const source = new Database(':memory:');
    for (const file of readdirSync(migrationsDir)
      .filter((name) => name.endsWith('.sql'))
      .sort())
      source.exec(readFileSync(join(migrationsDir, file), 'utf8'));
    source.exec(
      "create table d1_migrations (id integer primary key autoincrement, name text unique); insert into d1_migrations (name) values ('0001_init.sql'), ('0002_x.sql');",
    );
    source
      .prepare('insert into schema_meta (key, value) values (?, ?)')
      .run('note', "it's; ATTACH DATABASE 'x' AS a; --\nline two\r");
    source.exec(
      "create view schema_keys as select key from schema_meta; create trigger schema_meta_touch after update on schema_meta begin update schema_meta set value = value where key = 'none'; end;",
    );
    const sql = dumpLikeD1(source);
    expect(sql).toContain('DELETE FROM sqlite_sequence;');
    expect(sql).toContain('char(10)');
    const path = join(dir, 'database.sql');
    writeFileSync(path, sql);
    const loaded = loadDump(path);
    const counts = describeDump(loaded).tables;
    // Every table round-trips with its row count.
    expect(counts).toEqual(describeDump(source).tables);
    expect(counts.d1_migrations).toBe(2);
    expect(loaded.prepare("select value from schema_meta where key = 'note'").pluck().get()).toBe(
      "it's; ATTACH DATABASE 'x' AS a; --\nline two\r",
    );
    loaded.close();
    source.close();
  });

  const target = () => join(dir, 'written-by-dump.db');
  it.each([
    [
      'ATTACH',
      (file: string) =>
        `PRAGMA defer_foreign_keys=TRUE;\nATTACH DATABASE '${file}' AS a;\nCREATE TABLE a.t (x);\n`,
    ],
    [
      'VACUUM INTO',
      (file: string) => `CREATE TABLE t (x);\nINSERT INTO t VALUES (1);\nVACUUM INTO '${file}';\n`,
    ],
    ['lower-case attach', (file: string) => `create table t (x);attach database '${file}' as a;`],
    ['ATTACH after a block comment', (file: string) => `/* export */ ATTACH '${file}' AS a;`],
    ['ATTACH after a line comment', (file: string) => `-- export\nATTACH '${file}' AS a;`],
    [
      'ATTACH after a string holding ;',
      (file: string) => `CREATE TABLE t (x);INSERT INTO t VALUES('a;b');ATTACH '${file}' AS a;`,
    ],
    [
      'ATTACH after a trigger',
      (file: string) =>
        `CREATE TABLE t (x);CREATE TRIGGER g AFTER INSERT ON t BEGIN SELECT 1; END;ATTACH '${file}' AS a;`,
    ],
    [
      'ATTACH folded into an unterminated trigger',
      (file: string) =>
        `CREATE TABLE t (x);CREATE TRIGGER g AFTER INSERT ON t BEGIN SELECT 1; ATTACH '${file}' AS a;`,
    ],
    ['another PRAGMA', () => `PRAGMA writable_schema=ON;`],
  ])('R-BAK-04 refuses a dump with %s and creates no file', (_case, build) => {
    const path = join(dir, 'database.sql');
    writeFileSync(path, build(target()));
    expect(() => loadDump(path)).toThrow();
    expect(existsSync(target())).toBe(false);
  });

  it('R-BAK-04 refuses ATTACH by keyword before running anything, and verify-backup says so', async () => {
    const path = join(dir, 'database.sql');
    writeFileSync(path, `CREATE TABLE t (x);\nATTACH DATABASE '${target()}' AS a;\n`);
    expect(() => loadDump(path)).toThrow(DumpRefusedError);
    expect(await runBackup(deps().deps)).toBe(0);
    const snapshot = snapshotDir();
    const sql = readFileSync(join(snapshot, 'database.sql'), 'utf8');
    writeFileSync(
      join(snapshot, 'database.sql'),
      `${sql}ATTACH DATABASE '${target()}' AS a;\nCREATE TABLE a.t (x);\n`,
    );
    reseal(snapshot);
    const { errors } = await verifySnapshot(snapshot);
    expect(errors).toContain(
      'database.sql holds a statement no D1 export contains (ATTACH); nothing in it was run.',
    );
    expect(existsSync(target())).toBe(false);
  });

  it('R-BAK-04 a ; or ATTACH inside a string literal is data, not a statement', () => {
    const path = join(dir, 'database.sql');
    writeFileSync(
      path,
      `CREATE TABLE t (x);\nINSERT INTO t VALUES('x; ATTACH DATABASE ''${target()}'' AS a; --');\n`,
    );
    const loaded = loadDump(path);
    expect(loaded.prepare('select count(*) from t').pluck().get()).toBe(1);
    loaded.close();
    expect(existsSync(target())).toBe(false);
  });
});
