function fakeStorage(objects: Map<string, Buffer>) {
  return {
    // One object per page, so pagination is exercised.
    list: vi.fn(async (prefix: string, cursor?: string) => {
      const keys = [...objects.keys()].filter((key) => key.startsWith(prefix)).sort();
      const index = cursor ? Number(cursor) : 0;
      const key = keys[index];
      return {
        objects: key ? [{ key, size: objects.get(key)!.length }] : [],
        ...(index + 1 < keys.length ? { cursor: String(index + 1) } : {}),
      };
    }),
    get: vi.fn(async (key: string, destination: string, size: number) => {
      const data = objects.get(key);
      if (!data) return null;
      expect(data.length).toBe(size);
      writeFileSync(destination, data, { flag: 'wx' });
      return { size: data.length, sha256: sha(data) };
    }),
  };
}

function fakeRun(live: Record<string, number | null | undefined> = {}, sql = dumpSql) {
  const calls: { args: string[]; input?: string }[] = [];
  const run = vi.fn((args: string[], options: { input?: string } = {}): CfResult => {
    calls.push({ args, input: options.input });
    const ok = (stdout = '{}') => ({ status: 0, stdout, stderr: '' });
    if (args[0] === 'api') return ok();
    if (args[0] === 'd1' && args[1] === 'export') {
      writeFileSync(args[args.indexOf('--output') + 1]!, sql);
      return ok('');
    }
    if (args[0] === 'd1-query') {
      const body = JSON.parse(options.input ?? '{}') as { sql: string; params: string[] };
      if (body.sql.startsWith('SELECT deleted_at FROM media')) {
        const id = body.params[0]!;
        const rows = id in live ? [[live[id] ?? null]] : [];
        return ok(JSON.stringify([{ results: { columns: ['deleted_at'], rows } }]));
      }
      if (body.sql.startsWith('INSERT INTO backup_runs')) return ok('[]');
    }
    return { status: 1, stdout: '', stderr: `unexpected ${args.join(' ')}` };
  });
  return { run, calls };
}

